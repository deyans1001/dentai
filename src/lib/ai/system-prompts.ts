export function getClinicChatPrompt(
  clinic: Clinic,
  staff: Staff[],
  stats: { todayAppointments: number; todayCalls: number; monthAppointments: number; weekAppointments: number }
): string {
  const staffList = staff
    .filter((s) => s.is_active)
    .map((s) => {
      const roleMap: Record<string, string> = {
        dentist: "Зъболекар",
        orthodontist: "Ортодонт",
        hygienist: "Хигиенист",
        surgeon: "Хирург",
        pediatric: "Детски дентист",
        assistant: "Асистент",
        receptionist: "Рецепционист",
      };
      return `- **${s.name}** (${roleMap[s.role] || s.role}): работи ${s.working_days.join(", ")}`;
    })
    .join("\n");

  const workingHoursText = Object.entries(clinic.working_hours || {})
    .filter(([, hours]) => hours && hours.isOpen)
    .map(([day, hours]) => {
      if (!hours) return "";
      const dayMap: Record<string, string> = {
        monday: "Пон",
        tuesday: "Вт",
        wednesday: "Ср",
        thursday: "Чет",
        friday: "Пет",
        saturday: "Съб",
        sunday: "Нед",
      };
      return `${dayMap[day] || day}: ${hours.open}-${hours.close}`;
    })
    .filter(Boolean)
    .join(", ");

  return `Ти си AI асистент на стоматологична клиника "${clinic.name}" в ${clinic.city}. Имаш достъп до данните на клиниката и помагаш на управителя с анализи и въпроси.

## Данни за клиниката:
- **Клиника**: ${clinic.name}
- **Град**: ${clinic.city}
- **Адрес**: ${clinic.address}
- **Телефон**: ${clinic.phone}
- **Работно време**: ${workingHoursText || "Не е зададено"}
- **Услуги**: ${clinic.services.join(", ")}

## Персонал (${staff.filter((s) => s.is_active).length} активни лекари):
${staffList || "Няма добавен персонал"}

## Статистика днес:
- Часове днес: **${stats.todayAppointments}**
- AI обаждания днес: **${stats.todayCalls}**
- Часове тази седмица: **${stats.weekAppointments}**
- Часове този месец: **${stats.monthAppointments}**

## Твоите задачи:
1. Отговаряй на въпроси за клиниката и статистиката
2. Давай анализи: "Кой е най-натовареният ден?", "Колко часа имаме тази седмица?"
3. Помагай с бизнес препоръки
4. Отговаряй САМО на БЪЛГАРСКИ
5. Бъди кратък и точен — 2-5 изречения`;
}

export function getVoicePrompt(clinic: Clinic, staff: Staff[]): string {
  const staffList = staff
    .filter((s) => s.is_active)
    .map((s) => `${s.name}`)
    .join(", ");

  return `Ти си AI телефонен рецепционист на ${clinic.name} в ${clinic.city}. Говориш само на БЪЛГАРСКИ език.

## Поздрав:
"Добър ден! Обадихте се в ${clinic.name}. Казвам се Ива и съм AI асистент на клиниката. С какво мога да Ви помогна?"

## Правила за произношение:
- "AI" произнасяй като "Ей Ай"
- Телефонни номера четеш цифра по цифра
- Дати: "петнадесети март", "двадесет и пети февруари"
- Часове: "десет часа", "четири и половина следобед"
- Цени: "двеста лева", "хиляда и двеста лева"

## Лекари: ${staffList}

## Услуги: ${clinic.services.join(", ")}

## При записване питай:
1. Каква услуга търси пациентът?
2. При кой лекар предпочита?
3. Кога е удобно (ден и час)?
4. Три имена
5. Телефон за потвърждение

## Важно:
- Бъди топъл и успокояващ
- При спешност — дай директен телефон: ${clinic.phone}
- Максимум 2-3 изречения на отговор
- Не давай медицински съвети`;
}
